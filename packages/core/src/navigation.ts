import {
  compare,
  foldCase,
  type Config,
  type DocumentRecord,
  type NavEntry,
  type NavigationItem,
  type Diagnostic,
} from "@doc-base/schema";
import path from "node:path";
import { diagnostic } from "@doc-base/schema";
export function navigation(
  config: Readonly<Config>,
  documents: readonly Readonly<DocumentRecord>[],
  audience: string | null,
  url: (doc: Readonly<DocumentRecord>) => string,
  resolve: (ref: string) => Readonly<DocumentRecord> | undefined,
  diagnostics: Diagnostic[],
  allDocuments: readonly Readonly<DocumentRecord>[],
): NavEntry[] {
  if (!config.navigation) {
    diagnostics.push(
      diagnostic(
        "DBN100",
        "Native Starlight navigation does not provide audience-specific sidebar guarantees",
        { severity: "warning", suppressible: true },
      ),
    );
    return [];
  }
  const seen = new Set<string>();
  const visible = new Map(documents.map((doc) => [doc.key, doc]));
  const entry = (doc: Readonly<DocumentRecord>, label?: string): NavEntry => {
    if (seen.has(doc.key))
      diagnostics.push(
        diagnostic("DBN210", `Duplicate navigation entry ${doc.key}`, {
          documentKey: doc.key,
          sourceId: doc.sourceId,
          file: doc.sourcePath,
        }),
      );
    seen.add(doc.key);
    return { label: label ?? doc.nav.label, link: url(doc) };
  };
  const generate = (source: string, directory: string): NavEntry[] => {
    const directoryPath = path.posix
      .normalize(
        path.posix.join(
          (config.sources[source]?.content ?? ".").replace(/\\/g, "/"),
          directory.replace(/\\/g, "/"),
        ),
      )
      .normalize("NFC");
    const prefix =
      directoryPath === "."
        ? ""
        : directoryPath.replace(/^\/+|\/+$/g, "") + "/";
    if (!config.sources[source] || directory.split(/[\\/]/).includes("..")) {
      diagnostics.push(
        diagnostic(
          "DBN110",
          `Invalid navigation source/directory ${source}/${directory}`,
        ),
      );
      return [];
    }
    const selected = documents
      .filter(
        (doc) =>
          doc.sourceId === source &&
          doc.sourcePath.startsWith(prefix) &&
          !doc.nav.hidden,
      )
      .sort(
        (a, b) =>
          (a.nav.order ?? Infinity) - (b.nav.order ?? Infinity) ||
          compare(foldCase(a.nav.label), foldCase(b.nav.label)) ||
          compare(a.key, b.key),
      );
    if (
      !allDocuments.some(
        (doc) => doc.sourceId === source && doc.sourcePath.startsWith(prefix),
      ) &&
      allDocuments.some((doc) => doc.sourceId === source)
    )
      diagnostics.push(
        diagnostic(
          "DBN110",
          `No documents match autogenerated navigation ${source}/${directory}`,
        ),
      );
    const directoryLabels = new Map<string, string>();
    for (const doc of selected)
      if (doc.nav.group) {
        const directory = path.posix.dirname(doc.sourcePath);
        const label = directoryLabels.get(directory);
        if (label && label !== doc.nav.group)
          diagnostics.push(
            diagnostic(
              "DBN230",
              `Conflicting nav.group values in ${source}/${directory}`,
            ),
          );
        else directoryLabels.set(directory, doc.nav.group);
      }
    const groups = new Map<string, NavEntry>();
    const result: NavEntry[] = [];
    for (const doc of selected) {
      const folders = doc.sourcePath
        .slice(prefix.length)
        .split("/")
        .slice(0, -1);
      let target = result;
      let groupPath = "";
      for (let index = 0; index < folders.length; index++) {
        const folder = folders[index];
        groupPath += "/" + folder;
        const label =
          directoryLabels.get(
            prefix.replace(/\/$/, "") +
              groupPath.replace(/^\//, prefix ? "/" : ""),
          ) ??
          folder
            .replace(/[-_]/g, " ")
            .replace(/\b\w/g, (char) => char.toUpperCase());
        let group = groups.get(groupPath);
        if (!group) {
          group = { label, items: [] };
          groups.set(groupPath, group);
          target.push(group);
        }
        target = group.items!;
      }
      target.push(entry(doc));
    }
    return result;
  };
  const build = (items: NavigationItem[]): NavEntry[] =>
    items.flatMap((item) => {
      if (item.audiences?.some((id) => !config.audiences[id]))
        diagnostics.push(diagnostic("DBA100", "Unknown navigation audience"));
      if (item.audiences && (!audience || !item.audiences.includes(audience)))
        return [];
      if ("doc" in item) {
        const doc = resolve(item.doc);
        if (!doc) {
          diagnostics.push(
            diagnostic(
              "DBN200",
              `Missing or ambiguous navigation target ${item.doc}`,
            ),
          );
          return [];
        }
        if (!visible.has(doc.key)) return [];
        const result = entry(doc, item.label);
        const fragment = item.doc.split("#")[1];
        if (fragment) result.link += "#" + fragment;
        return [result];
      }
      if ("group" in item) {
        const children = build(item.items);
        return children.length
          ? [{ label: item.group, items: children, collapsed: item.collapsed }]
          : [];
      }
      if ("link" in item)
        return [{ label: item.link.label, link: item.link.href }];
      return generate(item.autogenerate.source, item.autogenerate.directory);
    });
  const result = build(config.navigation);
  if (config.validation.strictNavigation)
    for (const doc of documents)
      if (!seen.has(doc.key))
        diagnostics.push(
          diagnostic(
            "DBN220",
            `Visible page ${doc.key} is omitted from navigation`,
            {
              severity: "warning",
              suppressible: true,
              documentKey: doc.key,
              sourceId: doc.sourceId,
              file: doc.sourcePath,
            },
          ),
        );
  return result;
}
